# Generates src/s2_unicode_tables.h (letter / number / whitespace ranges for the pre-tokenizer).
#
# The tables must follow the Unicode version of the regex engine the reference tokenizer runs on, not
# the Python that happens to run this script: Hugging Face `tokenizers` matches the tokenizer.json regex
# with Oniguruma (onig_sys 69.9.x = Oniguruma 6.9.10), whose \p{L} / \p{N} are Unicode 16.0.0.
# With other tables a newly assigned letter (e.g. U+2EBF0) is split off the run it belongs to,
# which changes the BPE token ids.
#
# usage: python scripts/gen_unicode.py src/s2_unicode_tables.h [path/to/UnicodeData.txt]
# Without a path, UnicodeData.txt of UNICODE_VERSION is downloaded from unicode.org.
import sys
import urllib.request

UNICODE_VERSION = "16.0.0"

def load_categories(path):
    """General_Category of every code point (Cn for unassigned), from UnicodeData.txt."""
    if path:
        with open(path, encoding="utf-8") as f:
            lines = f.read().splitlines()
    else:
        url = "https://www.unicode.org/Public/%s/ucd/UnicodeData.txt" % UNICODE_VERSION
        with urllib.request.urlopen(url) as r:
            lines = r.read().decode("utf-8").splitlines()
    cats = ["Cn"] * 0x110000
    first = None
    for line in lines:
        if not line:
            continue
        fields = line.split(";")
        cp, name, gc = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            first = cp
        elif name.endswith(", Last>"):
            for c in range(first, cp + 1):
                cats[c] = gc
            first = None
        else:
            cats[cp] = gc
    return cats

def ranges(pred):
    out = []
    start = None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out

cats = load_categories(sys.argv[2] if len(sys.argv) > 2 else None)

L = ranges(lambda c: cats[c].startswith("L"))
N = ranges(lambda c: cats[c].startswith("N"))
# Unicode White_Space property (what regex \s matches in the tokenizers crate)
WS = [(9, 13), (32, 32), (0x85, 0x85), (0xA0, 0xA0), (0x1680, 0x1680), (0x2000, 0x200A),
      (0x2028, 0x2029), (0x202F, 0x202F), (0x205F, 0x205F), (0x3000, 0x3000)]

def emit(name, rs):
    s = "static const uint32_t %s[][2] = {\n" % name
    line = "  "
    for a, b in rs:
        item = "{0x%X,0x%X}," % (a, b)
        if len(line) + len(item) > 100:
            s += line + "\n"
            line = "  "
        line += item
    s += line + "\n};\n"
    return s

with open(sys.argv[1], "w", newline="\n") as f:
    f.write("// Generated by scripts/gen_unicode.py from Unicode %s (the version of the Oniguruma used by Hugging Face tokenizers)\n" % UNICODE_VERSION)
    f.write("#pragma once\n#include <cstdint>\nnamespace s2 {\n")
    f.write(emit("kUniLetter", L))
    f.write(emit("kUniNumber", N))
    f.write(emit("kUniSpace", WS))
    f.write("}\n")
print(len(L), len(N))
